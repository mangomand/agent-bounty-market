#!/usr/bin/env bash
# Regenerates the viem-ready ABI modules in packages/shared/src/abi/ from forge artifacts.
set -euo pipefail
cd "$(dirname "$0")/.."
forge build >/dev/null
out=../packages/shared/src/abi
mkdir -p "$out"
emit() { # <Contract> <exportName> <file>
  {
    echo "// Generated by contracts/script/export-abi.sh. Do not edit by hand."
    printf "export const %s = %s as const;\n" "$2" "$(jq '.abi' "out/$1.sol/$1.json")"
  } >"$out/$3"
}
emit BountyEscrow bountyEscrowAbi bountyEscrow.ts
emit MockUSDC mockUsdcAbi mockUsdc.ts
echo "wrote $out/bountyEscrow.ts and $out/mockUsdc.ts"
